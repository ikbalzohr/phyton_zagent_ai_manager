from typing import Protocol, Any

class ArcMapLivePort(Protocol):
    def inspect_identity(self) -> dict[str, Any]: ...
    def snapshot_state(self, *, expected_context: dict[str, Any]) -> dict[str, Any]: ...
    def validate_recipe(self, recipe: dict[str, Any]) -> dict[str, Any]: ...
    def apply_recipe(self, recipe: dict[str, Any], *, expected_context: dict[str, Any], fencing_epoch: int) -> dict[str, Any]: ...
    def verify_postconditions(self, postconditions: list[Any], *, expected_context: dict[str, Any]) -> dict[str, Any]: ...
    def restore_snapshot(self, checkpoint: dict[str, Any], *, expected_context: dict[str, Any], fencing_epoch: int) -> dict[str, Any]: ...
