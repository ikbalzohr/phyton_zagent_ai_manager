from typing import Protocol, Any

class FileWorkerPort(Protocol):
    def probe(self) -> dict[str, Any]: ...
    def prepare_template(self, *, template_mxd: str, data_root: str, workspace: str, goal: dict[str, Any]) -> dict[str, Any]: ...
    def prepare_blank(self, *, data_root: str, workspace: str, goal: dict[str, Any], disposable: bool) -> dict[str, Any]: ...
    def render_staging(self, *, working_mxd: str, staging_dir: str, outputs: dict[str, Any], base_name: str = "") -> dict[str, Any]: ...
