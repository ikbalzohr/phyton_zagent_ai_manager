from typing import Protocol, Any

class MapEnginePort(Protocol):
    """Future-engine boundary; ArcMap 10.6.1 remains the current implementation target."""
    def capabilities(self) -> dict[str,Any]: ...
    def collect_context(self,target: dict[str,Any]) -> dict[str,Any]: ...
    def execute_plan(self,plan: dict[str,Any],context: dict[str,Any]) -> dict[str,Any]: ...
    def validate(self,context: dict[str,Any],profile: dict[str,Any]) -> dict[str,Any]: ...
    def publish(self,artifacts: list[dict[str,Any]],policy: dict[str,Any]) -> dict[str,Any]: ...
